const fs = require('fs')
const path = require('path')
const cheerio = require('cheerio')

const docsDir = path.join(__dirname, '..', 'public', 'docs', 'user-guide')
const localesDir = path.join(docsDir, 'locales')
const potPath = path.join(localesDir, 'messages.pot')

// Ensure locales directory exists
if (!fs.existsSync(localesDir)) {
  fs.mkdirSync(localesDir, { recursive: true })
}

// Get all HTML files in the root docs dir (not subdirectories)
const htmlFiles = fs.readdirSync(docsDir).filter(f => f.endsWith('.html'))
console.log(`Found ${htmlFiles.length} HTML files: ${htmlFiles.join(', ')}`)

const seen = new Set()
const strings = []

function addString(str) {
  const trimmed = str.trim()
  // Skip empty or whitespace-only strings
  if (!trimmed) return
  // Skip strings that are only icons (e.g. <i class="..."></i>)
  if (/^<i\s[^>]*><\/i>$/.test(trimmed)) return
  // Deduplicate
  if (seen.has(trimmed)) return
  seen.add(trimmed)
  strings.push(trimmed)
}

for (const file of htmlFiles) {
  const filePath = path.join(docsDir, file)
  const html = fs.readFileSync(filePath, 'utf8')
  const $ = cheerio.load(html)

  // title tag
  const titleText = $('title').text().trim()
  if (titleText) addString(titleText)

  // .nav-group-title
  $('.nav-group-title').each((_, el) => {
    addString($(el).text())
  })

  // nav .nav-item span and nav .nav-sub span — only the span text, not the icon
  $('nav .nav-item span, nav .nav-sub span').each((_, el) => {
    addString($(el).text())
  })

  // .breadcrumb span (last breadcrumb segment)
  $('.breadcrumb span').each((_, el) => {
    addString($(el).text())
  })

  // h2, h3, h4 inside .content
  $('.content h2, .content h3, .content h4').each((_, el) => {
    addString($(el).text())
  })

  // p inside .content — preserve innerHTML
  $('.content p').each((_, el) => {
    addString($(el).html())
  })

  // li inside .content — preserve innerHTML
  $('.content li').each((_, el) => {
    addString($(el).html())
  })

  // .tip — innerHTML
  $('.tip').each((_, el) => {
    addString($(el).html())
  })
}

console.log(`Extracted ${strings.length} unique strings`)

// Escape a string for PO format
function poEscape(str) {
  return str
    .replace(/\\/g, '\\\\')
    .replace(/"/g, '\\"')
    .replace(/\n/g, '\\n')
    .replace(/\r/g, '')
}

// Build POT content
const header = `# Docs i18n — Make Cargo User Guide
# Generated by docs-i18n-extract.js
#
msgid ""
msgstr ""
"Content-Type: text/plain; charset=UTF-8\\n"
"Content-Transfer-Encoding: 8bit\\n"
"MIME-Version: 1.0\\n"
`

const blocks = strings.map(s => `msgid "${poEscape(s)}"\nmsgstr ""`)
const potContent = header + '\n' + blocks.join('\n\n') + '\n'

fs.writeFileSync(potPath, potContent, 'utf8')
console.log(`Written ${strings.length} entries to ${potPath}`)
